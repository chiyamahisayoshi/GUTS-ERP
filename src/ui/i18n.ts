const chineseToJapanese = new Map(
  Object.entries(japaneseToChinese).map(([japanese, chinese]) => [chinese, japanese])
);
const japaneseEntries = Object.entries(japaneseToChinese).sort(([a], [b]) => b.length - a.length);
const chineseEntries = [...chineseToJapanese.entries()].sort(([a], [b]) => b.length - a.length);

export function translateText(value: string, language: Language): string {
  const entries = language === 'zh' ? japaneseEntries : chineseEntries;
  return entries.reduce((translated, [source, target]) =>
    translated.replaceAll(source, target), value);
}
